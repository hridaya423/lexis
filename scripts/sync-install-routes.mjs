// Regenerates app/<route>/script.ts embeds from the canonical scripts in
// scripts/install/ so the web-served installers can never drift from source.
// --check verifies freshness instead of writing (CI).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const targets = [
  { src: "scripts/install/install.sh", dest: "app/install.sh/script.ts", name: "INSTALL_SH" },
  { src: "scripts/install/win.ps1", dest: "app/win.ps1/script.ts", name: "INSTALL_PS1" },
];

let stale = false;
for (const { src, dest, name } of targets) {
  const content = fs.readFileSync(path.join(root, src), "utf8");
  const out = `// Generated by scripts/sync-install-routes.mjs from ${src}. Do not edit.\nexport const ${name} = ${JSON.stringify(content)};\n`;
  const destPath = path.join(root, dest);
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(destPath) || fs.readFileSync(destPath, "utf8") !== out) {
      console.error(`stale: ${dest} (run npm run sync:installers)`);
      stale = true;
    }
    continue;
  }
  fs.writeFileSync(destPath, out);
  console.log(`wrote ${dest}`);
}
if (stale) process.exit(1);
